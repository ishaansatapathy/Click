export interface SetupOptions {
  main: string;
  agents: Record<Seat, string>;
  check?: (cwd: string) => Promise<RunResult>;
  install?: (cwd: string) => Promise<RunResult>;
  now?: () => Date;
  log?: (line: string) => void;
}

export interface SetupResult {
  created: Seat[];
  existing: Seat[];
  gitignoreCommitted: boolean;
}

const IGNORE_LINES = ['coord/', '.pair.json'];

/** Add the pair-mode ignore lines if missing. Pure, for testing. */
export function ensureGitignore(text: string): { text: string; changed: boolean } {
  const have = new Set(text.split(/\r?\n/).map((l) => l.trim()));
  const missing = IGNORE_LINES.filter((l) => !have.has(l));
  if (missing.length === 0) return { text, changed: false };
  const sep = text === '' || text.endsWith('\n') ? '' : '\n';
  return { text: `${text}${sep}\n# Pair mode (PLAN §14)\n${missing.join('\n')}\n`, changed: true };
}

/** The Pair Preamble (PROMPTS.md) with this seat's values filled in. Written as CLAUDE.md and AGENTS.md. */
export function renderPreamble(p: { seat: Seat; agent: string; main: string; worktree: string }): string {
  const S = p.seat.toUpperCase();
  const other = p.seat === 'a' ? 'B' : 'A';
  return `<!-- Generated by \`pnpm pair:setup\`. Do not edit: re-run setup instead. -->
# Click · Seat ${S} (${p.agent}) · PAIR MODE

You are Seat ${S} (${p.agent}) building Click. Seat ${other} works in parallel on the other lane, in its own worktree.

- Your worktree: \`${p.worktree}\` (branch \`${branchFor(p.seat)}\`)
- MAIN: \`${p.main}\`. Docs and coordination live **only** there: read PLAN.md §3, §4, §14, the SPEC.md sections the
  prompt names, and the prompt itself in PROMPTS.md from MAIN. They are not in your worktree.
- Your lane and its files: PLAN §14.4 (\`scripts/pair/ownership.json\`). Your queue: PROMPTS.md → "Pair dispatch", Seat ${S}.

## Before each prompt
1. \`pnpm pair:status\`. Open requests addressed to you come first (they beat your queue).
2. If the prompt has a WAIT tag that doesn't exist yet, use template T10 instead.
3. \`pnpm pair:mark <NNN> working\`

## While working
- Edit only paths your lane owns. Shared files (package.json, lockfile, config.ts, …): a tiny separate commit, synced at once.
  Frozen files (types.ts, store/types.ts, contracts.ts) or SPEC changes: template T9 to Ishaan.
- Never edit tracked files in MAIN. Never resolve a conflict in a file you don't own.
- ${p.seat === 'b' ? 'You are Seat B: never make paid API calls. Use the fakes in packages/core/src/testing and recorded fixtures.' : 'You are Seat A: you own every paid API call (Anthropic, Voyage, HydraDB, Jev, rerank). Cache everything.'}
- Anything Seat ${other} must read goes to \`${p.main}/coord/requests/\` (template T9), not into a .md in your worktree.
- TypeScript strict, ESM, small modules, a Vitest test for everything you add. Verify external APIs against live docs.
  Secrets only from env. Hooks never write to stdout except protocol output.

## After each prompt
\`pnpm check\` → commit \`${S}/<NNN>: summary\` → \`pnpm pair:sync\` (add \`--tag <tag>\` if your queue says the prompt emits one)
→ \`pnpm pair:mark <NNN> done\`. Append decisions to \`${p.main}/DECISIONS.md\` with \`>>\` only, one line, never rewrite it.
If \`pair:sync\` refuses, follow template T8.
`;
}

async function mustGit(args: string[], cwd: string): Promise<string> {
  return git(args, cwd);
}

/** Same directory? realpath expands Windows 8.3 short names (ISHAAN~1), which git never prints. */
function samePath(a: string, b: string): boolean {
  const n = (p: string) => {
    let full = resolve(p);
    try {
      full = realpathSync.native(full);
    } catch {
      // not created yet: compare the resolved form
    }
    return full.replace(/\\/g, '/').replace(/\/+$/, '');
  };
  return process.platform === 'win32' ? n(a).toLowerCase() === n(b).toLowerCase() : n(a) === n(b);
}

async function listWorktrees(main: string): Promise<string[]> {
  const out = await mustGit(['worktree', 'list', '--porcelain'], main);
  return out
    .split(/\r?\n/)
    .filter((l) => l.startsWith('worktree '))
    .map((l) => l.slice('worktree '.length));
}

export async function setup(o: SetupOptions): Promise<SetupResult> {
  const log = o.log ?? ((l: string) => process.stdout.write(l + '\n'));
  const now = o.now ?? (() => new Date());
  const main = resolve(o.main);

  // 1. MAIN must be on main, with no tracked changes, and green.
  const branch = (await mustGit(['symbolic-ref', '--short', 'HEAD'], main)).trim();
  if (branch !== 'main') throw new Error(`MAIN must have "main" checked out (found "${branch}")`);
  if ((await mustGit(['status', '--porcelain', '--untracked-files=no'], main)).trim()) {
    throw new Error('MAIN has uncommitted changes to tracked files: commit or stash them first');
  }
  if (o.check) {
    log('Running pnpm check in MAIN…');
    const r = await o.check(main);
    if (r.code !== 0) throw new Error(`pnpm check failed in MAIN; fix main first.\n${tail(r.stdout + r.stderr)}`);
  }

  // 2. Ignore coord/ and .pair.json, committed before the worktrees branch off.
  const giPath = join(main, '.gitignore');
  const gi = ensureGitignore(existsSync(giPath) ? readFileSync(giPath, 'utf8') : '');
  if (gi.changed) {
    writeFileSync(giPath, gi.text, 'utf8');
    await mustGit(['add', '.gitignore'], main);
    await mustGit(['commit', '-q', '-m', 'pair: ignore coord/ and .pair.json'], main);
    log('Committed .gitignore update (shared, its own commit).');
  }

  // 3. Worktrees.
  const existingTrees = await listWorktrees(main);
  const created: Seat[] = [];
  const existing: Seat[] = [];
  for (const seat of SEATS) {
    const wt = worktreePath(main, seat);
    const br = branchFor(seat);
    if (existingTrees.some((p) => samePath(p, wt))) {
      existing.push(seat);
    } else {
      const hasBranch = (await run('git', ['rev-parse', '--verify', '--quiet', `refs/heads/${br}`], { cwd: main })).code === 0;
      await mustGit(hasBranch ? ['worktree', 'add', wt, br] : ['worktree', 'add', '-b', br, wt, 'main'], main);
      created.push(seat);
      log(`Created worktree ${wt} on ${br}.`);
    }
    if (o.install) {
      log(`Installing dependencies in ${wt}…`);
      const r = await o.install(wt);
      if (r.code !== 0) throw new Error(`pnpm install failed in ${wt}\n${tail(r.stdout + r.stderr)}`);
    }
    writeJsonAtomic(join(wt, '.pair.json'), { seat, main, worktree: wt });
    for (const linked of linkShared(main, wt)) log(`Linked ${linked} → MAIN`);
    const preamble = renderPreamble({ seat, agent: o.agents[seat], main, worktree: wt });
    writeFileSync(join(wt, 'CLAUDE.md'), preamble, 'utf8');
    writeFileSync(join(wt, 'AGENTS.md'), preamble, 'utf8');
  }

  // 4. Coordination files in MAIN.
  mkdirSync(join(requestsDir(main), 'done'), { recursive: true });
  const pair: PairJson = {
    v: 1,
    main,
    createdAt: now().toISOString(),
    seats: {
      a: { worktree: worktreePath(main, 'a'), branch: branchFor('a'), agent: o.agents.a },
      b: { worktree: worktreePath(main, 'b'), branch: branchFor('b'), agent: o.agents.b },
    },
  };
  writeJsonAtomic(pairJsonPath(main), pair);
  for (const seat of SEATS) if (!existsSync(statusPath(main, seat))) writeStatus(main, initialStatus(seat, now()));

  log(`Pair mode ready. Seat A (${o.agents.a}): ${pair.seats.a.worktree}  Seat B (${o.agents.b}): ${pair.seats.b.worktree}`);
  return { created, existing, gitignoreCommitted: gi.changed };
}

/**
 * Gitignored resources both seats must share, linked from each worktree to MAIN (PLAN §14.11):
 * - bench/repo: one clone of the benchmark repo;
 * - .click/cache: content-addressed API-response cache (atomic writes), so no paid call is made twice.
 * Junctions on Windows need no admin rights. Existing paths are left alone.
 */
export const SHARED_LINKS = [
  { path: 'bench/repo', createInMain: false },
  { path: '.click/cache', createInMain: true },
] as const;

export function linkShared(main: string, wt: string): string[] {
  const linked: string[] = [];
  for (const { path, createInMain } of SHARED_LINKS) {
    const target = join(main, path);
    const link = join(wt, path);
    if (!existsSync(target)) {
      if (!createInMain) continue;
      mkdirSync(target, { recursive: true });
    }
    if (existsSync(link)) continue;
    mkdirSync(dirname(link), { recursive: true });
    symlinkSync(target, link, process.platform === 'win32' ? 'junction' : 'dir');
    linked.push(path);
  }
  return linked;
}

const tail = (s: string, n = 30): string => s.trim().split(/\r?\n/).slice(-n).join('\n');

function argValue(args: string[], flag: string): string | undefined {
  const i = args.indexOf(flag);
  return i >= 0 ? args[i + 1] : undefined;
}

async function main(): Promise<void> {
  const args = process.argv.slice(2);
  const root = (await git(['rev-parse', '--show-toplevel'], process.cwd())).trim();
  await setup({
    main: root,
    agents: { a: argValue(args, '--a-agent') ?? 'codex', b: argValue(args, '--b-agent') ?? 'claude' },
    check: args.includes('--skip-check') ? undefined : (cwd) => runPnpm(['check'], { cwd }),
    install: args.includes('--no-install') ? undefined : (cwd) => runPnpm(['install', '--frozen-lockfile'], { cwd }),
  });
}

